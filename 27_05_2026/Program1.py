# sets :  
# 1. sets are unordered collection of items.
# 2. sets are unindexed.
# 3. sets are mutable.
# 4. sets do not allow duplicate items.
# creating a set :
my_set = {10, 20, 30, 40, 50} 
# printing a set :
print(my_set)
# add the elements 
# add 
my_set.add(100)
print("After adding element : ",my_set)
# update 
lst = [1,2,3,4,5]
my_set.update(lst)
print(my_set)